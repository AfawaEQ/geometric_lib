class Square:
    def area(a):
        '''
        Принимает сторону квадрата a, возвращает площадь квадрата со стороной a
        area(6) вернёт 36 
        '''
        return a * a

    def perimeter(a):
        '''
        Принимает сторону квадрата a, возвращает периметр квадрата со стороной a
        perimeter(6) вернёт 24
        '''
        return 4 * a
